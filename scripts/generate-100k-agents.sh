/// Entry flags bitfield
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct EntryFlags(u32);

impl EntryFlags {
    const NEW: u32 = 1 << 0;
    const MODIFIED: u32 = 1 << 1;
    const DELETED: u32 = 1 << 2;
    const COMPRESSED: u32 = 1 << 3;
    const ENCRYPTED: u32 = 1 << 4;
    
    pub fn new() -> Self {
        Self(Self::NEW)
    }
    
    pub fn is_new(&self) -> bool {
        (self.0 & Self::NEW) != 0
    }
    
    pub fn is_modified(&self) -> bool {
        (self.0 & Self::MODIFIED) != 0
    }
    
    pub fn mark_modified(&mut self) {
        self.0 |= Self::MODIFIED;
    }
}

