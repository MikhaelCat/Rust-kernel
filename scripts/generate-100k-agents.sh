agent_worker() {
    local agent_id="$1"
    local module="$2"
    local file="$3"
    local target_lines="$4"
    
    export PARALLEL_AGENT_ID="$agent_id"
    local start_time=$(date +%s.%N)
    
    log_agent "Starting generation for ${module} -> ${file}"
    
    # Generate code
    local output_file
    output_file=$(generate_agent_template "$agent_id" "$module" "$file" "$target_lines")
    
    if [[ -n "$output_file" && -f "$output_file" ]]; then
        local end_time=$(date +%s.%N)
        local duration=$(echo "$end_time - $start_time" | bc)
        local lines=$(wc -l < "$output_file")
        
        echo "${agent_id},${module},${output_file},${start_time},${end_time},SUCCESS,${lines}" >> "${AGENT_REGISTRY_FILE}"
        
        log_agent "Generated ${lines} lines in ${duration}s"
        ((GENERATED_LINES += lines)) || true
        ((COMPLETED_AGENTS++)) || true
    else
        echo "${agent_id},${module},${file},${start_time},,FAILED,0" >> "${AGENT_REGISTRY_FILE}"
        ((FAILED_AGENTS++)) || true
        log_agent "Failed to generate code", YELLOW
    fi
}

