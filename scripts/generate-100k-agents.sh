    fi
    
    execute_parallel_generation
    
    log_success "Code generation complete!"
    echo ""
    
    # Show file count
    local file_count=$(find "${KERNEL_DIR}/src" -name "*.rs" | wc -l)
    echo "Generated ${file_count} source files across all subsystems"
    echo ""
}

main "$@"
