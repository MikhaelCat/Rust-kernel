impl \${module_name^^} {
    /// Create new \${module_name} instance
    pub fn new(config: \${module_name^^}Config) -> Result<Self, \${module_name^^}Error> {
        if config.max_entries == 0 {
            return Err(\${module_name^^}Error::InvalidInput);
